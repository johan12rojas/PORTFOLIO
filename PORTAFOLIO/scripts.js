function applyTranslations(lang){
    const language = translations[lang] ? lang : 'en';
    const textMap = translations[language];
    const placeholderMap = placeholderTranslations[language];

    document.documentElement.setAttribute('lang', language);
    if(textMap['page.title']){
        document.title = textMap['page.title'];
    }

    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.dataset.i18n;
        if(key && textMap[key]){
            element.innerHTML = textMap[key];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.dataset.i18nPlaceholder;
        if(key && placeholderMap[key]){
            element.setAttribute('placeholder', placeholderMap[key]);
        }
    });

    document.querySelectorAll('[data-i18n-aria]').forEach(element => {
        const key = element.dataset.i18nAria;
        if(key && textMap[key]){
            element.setAttribute('aria-label', textMap[key]);
            element.setAttribute('title', textMap[key]);
        }
    });
}

function updateThemeToggleIcon(button){
    if(!button){
        return;
    }
    const icon = button.querySelector('i');
    if(!icon){
        return;
    }
    if(document.body.classList.contains('light-mode')){
        icon.classList.remove('fa-sun');
        icon.classList.add('fa-moon');
    }else{
        icon.classList.remove('fa-moon');
        icon.classList.add('fa-sun');
    }
}

function setActiveLanguageButton(lang){
    const buttons = document.querySelectorAll('.lang-btn');
    buttons.forEach(button => {
        const isActive = button.dataset.lang === lang;
        button.classList.toggle('lang-btn--active', isActive);
        button.setAttribute('aria-pressed', isActive);
    });
}

document.addEventListener('DOMContentLoaded', () => {
    const languageButtons = document.querySelectorAll('.lang-btn');
    const themeToggle = document.getElementById('theme-toggle');

    const storedLanguage = localStorage.getItem('portfolio-lang') || 'en';
    applyTranslations(storedLanguage);
    setActiveLanguageButton(storedLanguage);

    if(languageButtons.length){
        languageButtons.forEach(button => {
            button.addEventListener('click', () => {
                const selectedLang = button.dataset.lang;
                if(!selectedLang){
                    return;
                }
                applyTranslations(selectedLang);
                setActiveLanguageButton(selectedLang);
                localStorage.setItem('portfolio-lang', selectedLang);
                renderPortfolioPage(currentPage);
            });
        });
    }

    const storedTheme = localStorage.getItem('portfolio-theme') || 'dark';
    if(storedTheme === 'light'){
        document.body.classList.add('light-mode');
    }
    updateThemeToggleIcon(themeToggle);
    initParticleBackground();

    if(themeToggle){
        themeToggle.addEventListener('click', () => {
            document.body.classList.toggle('light-mode');
            const newTheme = document.body.classList.contains('light-mode') ? 'light' : 'dark';
            localStorage.setItem('portfolio-theme', newTheme);
            updateThemeToggleIcon(themeToggle);
            updateParticleTheme(newTheme);
        });
    }

    const portfolioProjects = Array.from(document.querySelectorAll('.portfolio .proyecto'));
    const prevBtn = document.getElementById('portfolio-prev');
    const nextBtn = document.getElementById('portfolio-next');
    const counter = document.getElementById('portfolio-counter');
    const controlsWrapper = document.querySelector('.portfolio-controls');
    const pageSize = 6;
    let currentPage = 0;

    function updatePortfolioControls(){
        const totalPages = Math.max(1, Math.ceil(portfolioProjects.length / pageSize));
        if(controlsWrapper){
            controlsWrapper.classList.toggle('portfolio-controls--hidden', totalPages <= 1);
        }
        if(counter){
            counter.textContent = `${currentPage + 1} / ${totalPages}`;
        }
        if(prevBtn){
            prevBtn.disabled = currentPage === 0;
        }
        if(nextBtn){
            nextBtn.disabled = currentPage >= totalPages - 1;
        }
    }

    function renderPortfolioPage(page){
        if(!portfolioProjects.length){
            return;
        }
        const totalPages = Math.max(1, Math.ceil(portfolioProjects.length / pageSize));
        currentPage = Math.min(Math.max(page, 0), totalPages - 1);
        const start = currentPage * pageSize;
        const end = start + pageSize;
        portfolioProjects.forEach((card, index) => {
            const visible = index >= start && index < end;
            card.classList.toggle('portfolio-hidden', !visible);
            if(visible){
                card.classList.remove('portfolio-fade-in');
                void card.offsetWidth;
                card.classList.add('portfolio-fade-in');
            }
        });
        updatePortfolioControls();
    }

    if(prevBtn){
        prevBtn.addEventListener('click', () => renderPortfolioPage(currentPage - 1));
    }
    if(nextBtn){
        nextBtn.addEventListener('click', () => renderPortfolioPage(currentPage + 1));
    }

    renderPortfolioPage(0);

    initRevealAnimations();

    efectoHabilidades();
});

window.addEventListener('scroll', efectoHabilidades);

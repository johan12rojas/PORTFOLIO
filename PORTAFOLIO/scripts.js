class Particle{
    constructor(system){
        this.system = system;
        this.colorIndex = 0;
        this.opacity = 0.6;
        this.margin = 40;
        this.setPalette(system.config.particleColors);
        this.reset(true);
    }

    setPalette(palette){
        const colors = Array.isArray(palette) && palette.length ? palette : ['rgba(255,255,255,0.4)'];
        if(this.colorIndex >= colors.length){
            this.colorIndex = this.colorIndex % colors.length;
        }
        if(this.colorIndex === 0){
            this.colorIndex = Math.floor(Math.random() * colors.length);
        }
        this.palette = colors;
        this.color = colors[this.colorIndex];
    }

    reset(initial = false){
        const { width, height, config } = this.system;
        const [minSize, maxSize] = config.sizeRange;
        this.size = minSize + Math.random() * (maxSize - minSize);
        this.vx = (Math.random() - 0.5) * config.maxVelocity * 2;
        this.vy = (Math.random() - 0.5) * config.maxVelocity * 2;
        this.opacity = 0.45 + Math.random() * 0.3;

        if(initial){
            this.x = Math.random() * width;
            this.y = Math.random() * height;
        }else{
            const edge = Math.floor(Math.random() * 4);
            switch(edge){
                case 0:
                    this.x = Math.random() * width;
                    this.y = -this.margin;
                    break;
                case 1:
                    this.x = width + this.margin;
                    this.y = Math.random() * height;
                    break;
                case 2:
                    this.x = Math.random() * width;
                    this.y = height + this.margin;
                    break;
                default:
                    this.x = -this.margin;
                    this.y = Math.random() * height;
            }
        }
    }

    update(){
        this.x += this.vx;
        this.y += this.vy;
        const { width, height } = this.system;
        if(this.x < -this.margin || this.x > width + this.margin || this.y < -this.margin || this.y > height + this.margin){
            this.reset();
        }
    }

    draw(ctx){
        ctx.beginPath();
        ctx.globalAlpha = this.opacity;
        ctx.fillStyle = this.color;
        ctx.arc(this.x, this.y, this.size, 0, Math.PI * 2);
        ctx.fill();
        ctx.globalAlpha = 1;
    }
}

class ParticleSystem{
    constructor(canvas, theme){
        this.canvas = canvas;
        this.ctx = canvas.getContext('2d');
        this.theme = PARTICLE_THEMES[theme] ? theme : 'dark';
        this.config = PARTICLE_THEMES[this.theme];
        this.dpr = window.devicePixelRatio || 1;
        this.width = window.innerWidth;
        this.height = window.innerHeight;
        this.particles = [];
        this.mouse = { x: null, y: null };

        this.animate = this.animate.bind(this);
        this.handleResize = this.handleResize.bind(this);
        this.handleMouseMove = this.handleMouseMove.bind(this);
        this.handleMouseLeave = this.handleMouseLeave.bind(this);

        this.handleResize();
        this.createParticles();

        window.addEventListener('resize', this.handleResize);
        window.addEventListener('mousemove', this.handleMouseMove);
        window.addEventListener('mouseleave', this.handleMouseLeave);

        this.animationFrame = requestAnimationFrame(this.animate);
    }

    handleResize(){
        this.dpr = window.devicePixelRatio || 1;
        this.width = window.innerWidth;
        this.height = window.innerHeight;
        this.canvas.width = this.width * this.dpr;
        this.canvas.height = this.height * this.dpr;
        this.canvas.style.width = `${this.width}px`;
        this.canvas.style.height = `${this.height}px`;
        this.adjustParticleCount();
    }

    getTargetParticleCount(){
        const area = this.width * this.height;
        const density = area / 12000;
        return Math.max(60, Math.min(160, Math.floor(density)));
    }

    adjustParticleCount(){
        const target = this.getTargetParticleCount();
        const current = this.particles.length;
        if(current < target){
            for(let i = current; i < target; i++){
                const particle = new Particle(this);
                this.particles.push(particle);
            }
        }else if(current > target){
            this.particles.splice(target);
        }
        const palette = this.config.particleColors;
        this.particles.forEach(particle => particle.setPalette(palette));
    }

    createParticles(){
        const target = this.getTargetParticleCount();
        this.particles = [];
        for(let i = 0; i < target; i++){
            this.particles.push(new Particle(this));
        }
        this.particles.forEach(particle => particle.setPalette(this.config.particleColors));
    }

    animate(){
        this.animationFrame = requestAnimationFrame(this.animate);
        const ctx = this.ctx;
        ctx.setTransform(this.dpr, 0, 0, this.dpr, 0, 0);
        ctx.clearRect(0, 0, this.width, this.height);
        this.particles.forEach(particle => {
            particle.update();
            particle.draw(ctx);
        });
        this.drawConnections(ctx);
    }

    drawConnections(ctx){
        const { particles, config } = this;
        const { connectionDistance, connectionColor, connectionAlpha, pointerAlpha, lineWidth, neighborCount } = config;
        ctx.lineWidth = lineWidth;
        for(let i = 0; i < particles.length; i++){
            const particle = particles[i];
            for(let j = i + 1; j < particles.length && j < i + neighborCount; j++){
                const other = particles[j];
                const dx = particle.x - other.x;
                const dy = particle.y - other.y;
                const distance = Math.hypot(dx, dy);
                if(distance > connectionDistance){
                    continue;
                }
                const alpha = connectionAlpha * (1 - distance / connectionDistance);
                if(alpha <= 0.02){
                    continue;
                }
                ctx.strokeStyle = connectionColor;
                ctx.globalAlpha = alpha;
                ctx.beginPath();
                ctx.moveTo(particle.x, particle.y);
                ctx.lineTo(other.x, other.y);
                ctx.stroke();
            }
        }
        if(this.mouse.x !== null && this.mouse.y !== null){
            particles.forEach(particle => {
                const dx = particle.x - this.mouse.x;
                const dy = particle.y - this.mouse.y;
                const distance = Math.hypot(dx, dy);
                const maxPointerDistance = connectionDistance * 0.85;
                if(distance < maxPointerDistance){
                    const alpha = pointerAlpha * (1 - distance / maxPointerDistance);
                    if(alpha <= 0.02){
                        return;
                    }
                    ctx.strokeStyle = connectionColor;
                    ctx.globalAlpha = alpha;
                    ctx.beginPath();
                    ctx.moveTo(particle.x, particle.y);
                    ctx.lineTo(this.mouse.x, this.mouse.y);
                    ctx.stroke();
                }
            });
        }
        ctx.globalAlpha = 1;
    }

    handleMouseMove(event){
        const rect = this.canvas.getBoundingClientRect();
        this.mouse.x = (event.clientX - rect.left);
        this.mouse.y = (event.clientY - rect.top);
    }

    handleMouseLeave(){
        this.mouse.x = null;
        this.mouse.y = null;
    }

    setTheme(theme){
        const newTheme = PARTICLE_THEMES[theme] ? theme : 'dark';
        if(newTheme === this.theme){
            return;
        }
        this.theme = newTheme;
        this.config = PARTICLE_THEMES[this.theme];
        this.particles.forEach(particle => particle.setPalette(this.config.particleColors));
    }

    destroy(){
        cancelAnimationFrame(this.animationFrame);
        window.removeEventListener('resize', this.handleResize);
        window.removeEventListener('mousemove', this.handleMouseMove);
        window.removeEventListener('mouseleave', this.handleMouseLeave);
        this.ctx.setTransform(1, 0, 0, 1, 0, 0);
        this.ctx.clearRect(0, 0, this.canvas.width, this.canvas.height);
        this.particles = [];
    }
}

function initParticleBackground(){
    const canvas = document.getElementById('bg-particles');
    if(!canvas){
        return;
    }
    if(!particleMotionListenerAttached){
        prefersReducedMotion.addEventListener('change', () => {
            if(particleSystem){
                particleSystem.destroy();
                particleSystem = null;
            }
            if(prefersReducedMotion.matches){
                canvas.style.display = 'none';
            }else{
                initParticleBackground();
            }
        });
        particleMotionListenerAttached = true;
    }
    if(prefersReducedMotion.matches){
        if(particleSystem){
            particleSystem.destroy();
            particleSystem = null;
        }
        canvas.style.display = 'none';
        return;
    }
    canvas.style.display = 'block';
    if(particleSystem){
        particleSystem.destroy();
    }
    const theme = document.body.classList.contains('light-mode') ? 'light' : 'dark';
    particleSystem = new ParticleSystem(canvas, theme);
}

function updateParticleTheme(theme){
    if(particleSystem){
        particleSystem.setTheme(theme);
    }
}

function ensureRevealObserver(){
    if(revealObserver){
        return revealObserver;
    }
    revealObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if(entry.isIntersecting){
                entry.target.classList.add('is-visible');
                revealObserver.unobserve(entry.target);
            }
        });
    }, { threshold: 0.15 });
    return revealObserver;
}

function registerRevealElement(element, { type = 'fade-up', delay } = {}){
    if(!element || element.dataset.revealInitialized){
        return;
    }
    element.dataset.revealInitialized = 'true';
    element.classList.add('reveal', `reveal--${type}`);
    if(delay){
        element.style.setProperty('--reveal-delay', delay);
    }
    if(prefersReducedMotion.matches){
        element.classList.add('is-visible');
        return;
    }
    const observer = ensureRevealObserver();
    observer.observe(element);
}

function applyReveal(selector, options = {}){
    const elements = typeof selector === 'string' ? document.querySelectorAll(selector) : selector;
    if(!elements || !elements.length){
        return;
    }
    elements.forEach((element, index) => {
        const delay = typeof options.stagger === 'number' ? `${index * options.stagger}s` : options.delay;
        registerRevealElement(element, { type: options.type, delay });
    });
}

